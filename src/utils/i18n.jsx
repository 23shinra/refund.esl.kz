const I18nContext = createContext(null);

export function I18nProvider({ children, initialLanguage = 'ru' }) {
  const [language, setLanguage] = useState(initialLanguage);

  const value = useMemo(() => {
    const langDict = dictionary[language] ?? dictionary.ru;

    const t = (path, vars) => {
      const parts = String(path).split('.');
      let cur = langDict;
      for (const p of parts) cur = cur?.[p];
      if (typeof cur === 'function') return cur(vars ?? {});
      return cur ?? path;
    };

    const tl = (localized) => {
      if (!localized) return '';
      if (typeof localized === 'string') return localized;
      return localized[language] ?? localized.ru ?? '';
    };

    return { language, setLanguage, t, tl };
  }, [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

I18nProvider.propTypes = {
  children: PropTypes.node,
  initialLanguage: PropTypes.oneOf(['ru', 'kz']),
};

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within I18nProvider');
  return ctx;
}

