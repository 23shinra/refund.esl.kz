function stableHash(input) {
  const s = String(input ?? '');
  let h = 0;
  for (let i = 0; i < s.length; i += 1) {
    h = (h * 31 + s.charCodeAt(i)) >>> 0;
  }
  return h;
}

export function getHelpersForCase(subcategoryCode, questionCode) {
  // Pick a single helper deterministically per service/question.
  // This makes names differ across services, while still allowing repeats.
  const seed = `${subcategoryCode ?? ''}|${questionCode ?? ''}`;
  const idx = stableHash(seed) % helpers.length;
  return [helpers[idx]];
}

